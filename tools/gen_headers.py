#!/usr/bin/env python3
"""Generate C headers for mods from data/<target>/ (functions, globals, structs, dvars)."""
import csv
import json
import re
import sys
from pathlib import Path

import target as targets
from ps3elf import Ps3Elf

ROOT = targets.ROOT
SIZES = {"char": 1, "bool": 1, "unsigned char": 1, "short": 2, "unsigned short": 2, "int": 4, "unsigned int": 4,
         "float": 4, "dvarType_t": 4, "scr_string_t": 4, "int64_t": 8, "DvarValue": 16, "DvarLimits": 16}
HEADER = "/* Generated by tools/gen_headers.py from data/{t}/ - do not edit. */\n"
COMMON_TYPES = {"opd_t", "dvarType_t", "scriptInstance_t", "scr_string_t", "DvarLimits", "jmp_buf",
                "errorParm_t", "svscmd_type", "DvarSetSource", "BuiltinFunction"}


def ident(name):
    return re.sub(r"\W", "_", name)


def type_size(t):
    t = t.strip()
    m = re.fullmatch(r"(.+?)\[(\d+)\]", t)
    if m:
        inner = type_size(m.group(1))
        return inner * int(m.group(2)) if inner else None
    if t.endswith("*"):
        return 4  # PS3 PPU: 32-bit pointers
    return SIZES.get(t)


def c_decl(t, name):
    m = re.fullmatch(r"(.+?)\[(\d+)\]", t.strip())
    return f"{m.group(1)} {name}[{m.group(2)}]" if m else f"{t} {name}"


def gen_structs(structs):
    out = [HEADER.format(t=TARGET), "#pragma once", '#include "types.h"', ""]
    # Types embedded by value (unions here) must be complete before their users.
    order = sorted((n for n in structs if not n.startswith("_")), key=lambda n: not structs[n].get("union"))
    for sname in order:
        s = structs[sname]
        size = int(s["size"], 16) if s.get("size") else None
        kind = "union" if s.get("union") else "struct"
        out.append(f"/* {s.get('evidence', '')} */")
        out.append(f"{kind} {sname}")
        out.append("{")
        pos, asserts = 0, []
        for f in sorted(s["fields"], key=lambda f: int(f["offset"], 16)):
            off, fsz = int(f["offset"], 16), type_size(f["type"])
            name = ident(f["name"])
            if fsz is None or (kind == "struct" and off < pos):
                out.append(f"    /* +0x{off:X} {f['type']} {f['name']} ({f['confidence']}) - not laid out */")
                continue
            if kind == "struct" and off > pos:
                out.append(f"    char _pad{pos:04X}[0x{off - pos:X}];")
            out.append(f"    {c_decl(f['type'], name)}; /* +0x{off:X} {f['confidence']} */")
            asserts.append(f"_Static_assert(offsetof({kind} {sname}, {name}) == 0x{off:X}, \"{sname}.{name}\");")
            pos = max(pos, off + fsz) if kind == "struct" else max(pos, fsz)
        if size and kind == "struct" and pos < size:
            out.append(f"    char _pad{pos:04X}[0x{size - pos:X}];")
        out.append("};")
        if size:
            asserts.append(f"_Static_assert(sizeof({kind} {sname}) == 0x{size:X}, \"sizeof {sname}\");")
        out += asserts + [""]
    return "\n".join(out)


def parse_proto(proto, name):
    m = re.fullmatch(r"\s*(.+?)\s*\b" + re.escape(name) + r"\s*\((.*)\)\s*", proto)
    return (m.group(1), m.group(2) or "void") if m else None


def gen_functions(funcs):
    out = [HEADER.format(t=TARGET), "#pragma once", '#include "types.h"', "",
           ]
    for r in funcs:
        name = ident(r["name"])
        addr = int(r["addr"], 16)
        notes = r["notes"].replace("*/", "* /").replace("/*", "/ *")
        out.append(f"/* {r['confidence']}: {notes} */")
        out.append(f"#define BO1_ADDR_{name} 0x{addr:08X}u")
        if r["opd"]:
            out.append(f"#define BO1_GAME_OPD_{name} 0x{int(r['opd'], 16):08X}u /* the game's own descriptor */")
        parsed = parse_proto(r["prototype"], r["name"]) if r["prototype"] else None
        if parsed:
            ret, args = parsed
            out.append(f"typedef {ret} (*{name}_t)({args});")
            out.append(f"static const opd_t bo1_opd_{name} = {{ 0x{addr:08X}u, BO1_TOC }};")
        out.append("")
    return "\n".join(out)


def gen_offsets(globs, dvars):
    out = [HEADER.format(t=TARGET), "#pragma once", "", f"#define BO1_TOC 0x{TOC:08X}u", ""]
    for r in globs:
        out.append(f"#define BO1_{ident(r['name'])} 0x{int(r['addr'], 16):08X}u /* {r['type']} ({r['confidence']}) */")
    out += ["", "/* dvar_t * globals filled by the Dvar_Register* call sites (first registration wins). */"]
    seen = set()
    for r in dvars:
        n = ident(r["name"])
        if r["dvar_ptr"] and n not in seen:
            seen.add(n)
            out.append(f"#define BO1_DVAR_{n} 0x{int(r['dvar_ptr'], 16):08X}u /* {r['type']} */")
    return "\n".join(out) + "\n"


DDL_TYPES = {0: "byte", 1: "short", 2: "uint", 3: "uint64", 4: "float", 5: "string", 6: "struct"}  # inferred from widths


def parse_ddl(path):
    """stats_ddl.txt -> (fields, enums); fields keyed by path without 'root.'."""
    fields, enums, cur = {}, [], None
    for line in path.read_text().splitlines():
        if line.startswith("root."):
            p, *kv = line.split()
            fields[p[5:]] = {k: int(v, 0) for k, v in (x.split("=") for x in kv)}
        elif line.startswith("enum "):
            cur = []
            enums.append(cur)
        elif line.strip() and cur is not None:
            cur.append(line.split()[1])
    return fields, enums


def gen_stats(stats, data):
    fields, enums = parse_ddl(data / stats["ddl"])
    data_ofs = int(stats["data_offset"], 16)
    out = [HEADER.format(t=TARGET), "#pragma once", '#include "offsets.h"', "",
           "/* Stats DDL (ddl_mp/stats.ddl) member offsets, relative to the DDL data of one buffer.",
           " * Bit fields are packed little-endian (DDL accessors use ldbrx/stdbrx): a byte-aligned",
           " * int member is stored byte-swapped relative to a PPU load. Array members give element 0. */",
           f"#define BO1_STATS_STRIDE 0x{int(stats['stride'], 16):X}u /* per controller */",
           f"#define BO1_STATS_BUFFER_SIZE 0x{int(stats['buffer_size'], 16):X}u",
           f"#define BO1_STATS_DATA 0x{data_ofs:X}u /* buffer header before the DDL data */",
           f"#define BO1_STATS_ADDR(controller, ofs) (BO1_{stats['buffers']} + (controller) * BO1_STATS_STRIDE"
           " + BO1_STATS_DATA + (ofs))", ""]
    for path, f in fields.items():
        typ = DDL_TYPES.get(f["type"], f"type{f['type']}")
        arr = f"[{f['array']}]" if f["array"] > 1 else ""
        out.append(f"#define BO1_STATS_{ident(path)} 0x{f['byte']:04X}u /* bit {f['bit']}, "
                   f"{f['element']} bits {typ}{arr} */")
    # Enum-indexed scalar arrays that are byte-aligned get one macro per entry.
    for path, f in fields.items():
        if f["type"] == 6 or f["array"] < 2 or f["enum"] < 0 or f["bit"] or f["element"] % 8:
            continue
        names = enums[f["enum"]]
        if len(names) != f["array"]:
            continue
        out += ["", f"/* {path}[{f['array']}] by enum {f['enum']} */"]
        out += [f"#define BO1_STATS_{ident(path)}_{ident(n)} 0x{f['byte'] + i * f['element'] // 8:04X}u"
                for i, n in enumerate(names)]
    return "\n".join(out) + "\n"


def collect_type_names(funcs, structs):
    known = set(structs) | COMMON_TYPES | {"DvarValue"}
    found = set()
    for r in funcs:
        found.update(re.findall(r"\b([A-Za-z_]\w*_t|DvarValue|DvarLimits|netadr_t|va_list|jmp_buf)\b", r["prototype"]))
        found.update(re.findall(r"\b([A-Z]\w*)\s*\*", r["prototype"]))  # opaque engine types used by pointer
    return sorted(found - known - {"size_t", "int64_t", "uint32_t", "va_list"})


def gen_common():
    return "\n".join([
        "/* Generated by tools/gen_headers.py - target-independent types. Do not edit. */",
        "#pragma once", "#include <stdint.h>", "#include <stddef.h>", "#include <stdbool.h>", "#include <stdarg.h>", "",
        "typedef struct opd_s { uint32_t func; uint32_t toc; } opd_t;",
        "typedef enum { SCRIPTINSTANCE_SERVER = 0, SCRIPTINSTANCE_CLIENT = 1 } scriptInstance_t;",
        "typedef unsigned int scr_string_t;",
        "typedef enum { DVAR_TYPE_BOOL, DVAR_TYPE_FLOAT, DVAR_TYPE_FLOAT_2, DVAR_TYPE_FLOAT_3, DVAR_TYPE_FLOAT_4,",
        "    DVAR_TYPE_INT, DVAR_TYPE_ENUM, DVAR_TYPE_STRING, DVAR_TYPE_COLOR, DVAR_TYPE_INT64,",
        "    DVAR_TYPE_LINEAR_COLOR_RGB, DVAR_TYPE_COLOR_XYZ } dvarType_t;",
        "typedef struct { union { struct { int min, max; } integer; struct { int64_t min, max; } integer64;",
        "    struct { float min, max; } value, vector; struct { int stringCount; const char **strings; } enumeration; }; } DvarLimits;",
        "typedef int jmp_buf[64]; /* opaque */",
        "typedef int errorParm_t;", "typedef int svscmd_type;", "typedef int DvarSetSource;",
        "typedef void (*BuiltinFunction)(void);", "",
        "/* Calling a game function from PPU code goes through an OPD {code, toc}.",
        " * BO1_FN(Name) yields a typed function pointer built from the static descriptor. */",
        "#define BO1_FN(name) ((name##_t)(const void *)&bo1_opd_##name)", ""])


def gen_ui_defines(rows):
    """data/ui_defines.csv (ui/menudefinition.h of the PC mod tools): ownerdraw/feeder/item type ids."""
    out = ["/* Generated by tools/gen_headers.py from data/ui_defines.csv (PC mod tools ui/menudefinition.h).",
           " * Do not edit. Values are the PC build's; check them against the EBOOT before relying on them. */",
           "#pragma once"]
    group = None
    for r in rows:
        if r["group"] != group:
            group = r["group"]
            out.append(f"\n/* {group} */")
        cond = f" /* {r['condition']} */" if r["condition"] else ""
        out.append(f"#define {r['name']} {r['value']}{cond}")
    return "\n".join(out) + "\n"


def gen_weapon_fields(rows):
    out = [HEADER.format(t=TARGET), "#pragma once",
           "/* Weapon def parse table (cspField_t): offsets into the loaded weapon def, as BG_* parse them. */", ""]
    for r in rows:
        out.append(f"#define BO1_WEAPFIELD_{ident(r['name'])} 0x{int(r['offset'], 16):X}u /* {r['type_name']} */")
    return "\n".join(dict.fromkeys(out)) + "\n"  # guidedMissileType is listed twice


def gen_dispatch():
    lines = ["/* Generated by tools/gen_headers.py. Build with -DBO1_TARGET_<T> to select the EBOOT. */",
             "#pragma once"]
    for i, t in enumerate(targets.TARGETS):
        lines += [f"#{'el' if i else ''}if defined(BO1_TARGET_{t.upper()})", f'#include "../bo1_{t}/bo1_{t}.h"']
    lines += ["#else", "#error \"define one of " + ", ".join(f"BO1_TARGET_{t.upper()}" for t in targets.TARGETS) + "\"",
              "#endif", ""]
    return "\n".join(lines)


def gen_types(funcs, structs):
    fwd = collect_type_names(funcs, structs)
    lines = [HEADER.format(t=TARGET), "#pragma once", '#include "../bo1/common.h"', '#include "offsets.h"', "",
             "typedef union DvarValue DvarValue;"]
    for s in structs:
        if not s.startswith("_") and s != "DvarValue":
            lines.append(f"typedef {'union' if structs[s].get('union') else 'struct'} {s} {s};")
    for t in fwd:
        lines.append(f"typedef int {t};" if t.endswith("type") else f"typedef struct {t} {t}; /* opaque */")
    if "scr_entref_t" in structs:
        lines.append("typedef void (*BuiltinMethod)(scr_entref_t);")
    lines.append("")
    return "\n".join(dict.fromkeys(lines))  # drop duplicate typedef lines


def main():
    global TARGET, TOC
    t = targets.get(sys.argv[1] if len(sys.argv) > 1 else None)
    TARGET, TOC = t.name, Ps3Elf(t.elf_path).toc
    data, out_dir = t.data_dir, t.include_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    common = ROOT / "include" / "bo1"
    common.mkdir(exist_ok=True)
    (common / "common.h").write_text(gen_common())
    (common / "bo1.h").write_text(gen_dispatch())
    if (ROOT / "data" / "ui_defines.csv").exists():
        (common / "ui_defines.h").write_text(gen_ui_defines(list(csv.DictReader((ROOT / "data" / "ui_defines.csv").open()))))
    rows = lambda f: list(csv.DictReader((data / f).open())) if (data / f).exists() else []
    funcs, globs, dvars = rows("functions.csv"), rows("globals.csv"), rows("dvars.csv")
    structs = json.loads((data / "structs.json").read_text()) if (data / "structs.json").exists() else {}
    (out_dir / "offsets.h").write_text(gen_offsets(globs, dvars))
    (out_dir / "types.h").write_text(gen_types(funcs, structs))
    (out_dir / "structs.h").write_text(gen_structs(structs))
    (out_dir / "functions.h").write_text(gen_functions(funcs))
    headers = ["offsets.h", "types.h", "structs.h", "functions.h"]
    if t.stats:
        (out_dir / "stats.h").write_text(gen_stats(t.stats, data))
        headers.append("stats.h")
    if weapon_fields := rows("weapon_def_fields.csv"):
        (out_dir / "weapon_fields.h").write_text(gen_weapon_fields(weapon_fields))
        headers.append("weapon_fields.h")
    (out_dir / f"bo1_{TARGET}.h").write_text(HEADER.format(t=TARGET) + "#pragma once\n" + "".join(
        f'#include "{h}"\n' for h in headers))
    print(f"headers written to {out_dir}")


if __name__ == "__main__":
    main()
